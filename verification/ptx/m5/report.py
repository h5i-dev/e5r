#!/usr/bin/env python3
"""Summarise results.json (from run.py) as RESULTS.md."""
import json, os, statistics as st, sys
here = os.path.dirname(os.path.abspath(__file__))
res = json.load(open(sys.argv[1]))
tasks = {t["name"]: t for t in json.load(open(os.path.join(here, "tasks.json")))}
rows = res["rows"]
nat = [r for r in rows if "seeded" not in tasks[r["name"]]]
seed = [r for r in rows if "seeded" in tasks[r["name"]]]
cnt = lambda rs, v: sum(r["verdict"] == v for r in rs)
proved = [r for r in rows if r["verdict"] == "proved"]
lt = sorted(r["lean_seconds"] for r in proved if r.get("lean_seconds"))
ratios = sorted(r["baseline_us"] / r["ptx_us"] for r in proved if r.get("ptx_us") and r.get("baseline_us"))
q = lambda xs, p: xs[min(len(xs) - 1, int(p * len(xs)))]
bad_gpu = [r["name"] for r in proved if r.get("gpu_mismatch") or r.get("gpu_error")]
out = [f"# M5 results ({res['gpu']})", "",
       "Generated by `report.py` from `results.json` (`run.py`). Every kernel in `kernels/` was",
       "written in this session by the agent (Claude, an LLM) from the task text in `tasks.json`;",
       "batch 4 shares one skeleton expanded from a table, with the instruction sequence per task",
       "written by the agent. Kernels marked seeded were written with a deliberate defect, or",
       "deliberately outside the subset, to test detection. They are not natural mistakes.", "",
       "| | kernels | proved | refuted | unknown | unsupported |", "|---|---|---|---|---|---|",
       f"| written to be correct | {len(nat)} | {cnt(nat,'proved')} | {cnt(nat,'refuted')} | {cnt(nat,'unknown')} | {cnt(nat,'unsupported')} |",
       f"| seeded defects | {len(seed)} | {cnt(seed,'proved')} | {cnt(seed,'refuted')} | {cnt(seed,'unknown')} | {cnt(seed,'unsupported')} |", "",
       f"- Lean proof time per proved kernel: median {st.median(lt):.1f} s, 90th percentile {q(lt,0.9):.1f} s, max {lt[-1]:.1f} s (one Lean thread).",
       f"- Speed, nvcc -O3 CUDA C baseline time / PTX time at n = 2^24 (median of 20): median {st.median(ratios):.2f}, range {ratios[0]:.2f} to {ratios[-1]:.2f}, over {len(ratios)} proved kernels.",
       f"- GPU test of proved kernels against their spec: {len(proved) - len(bad_gpu)} of {len(proved)} agree" + (f"; disagree: {bad_gpu}" if bad_gpu else "."),
       "", "| kernel | seeded | verdict | counterexample | Lean s | GPU test | baseline/PTX |", "|---|---|---|---|---|---|---|"]
for r in rows:
    t = tasks[r["name"]]
    sp = f"{r['baseline_us'] / r['ptx_us']:.2f}" if r.get("ptx_us") and r.get("baseline_us") else "-"
    g = "agrees" if not (r.get("gpu_mismatch") or r.get("gpu_error")) else "disagrees"
    reason = "" if r["verdict"] != "unsupported" else " (" + r["reasons"][0][:70].replace("|", "/") + ")"
    out.append(f"| {r['name']} | {t.get('seeded', '')} | {r['verdict']}{reason} | {r.get('counterexample') or ''} | {r.get('lean_seconds') or ''} | {g} | {sp} |")
open(os.path.join(here, "RESULTS.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out[:16]))
