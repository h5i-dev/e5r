#!/usr/bin/env python3
"""Write m4/RESULTS.md from results_first_run.json, results.json and
mutants_results.json (run4.py)."""
import json
import os
import statistics as st

here = os.path.dirname(os.path.abspath(__file__))
tasks = {t["name"]: t for t in json.load(open(os.path.join(here, "tasks.json")))}
first = {r["name"]: r for r in json.load(open(os.path.join(here, "results_first_run.json")))["rows"]}
rows = json.load(open(os.path.join(here, "results.json")))["rows"]
mpath = os.path.join(here, "mutants_results.json")
muts = json.load(open(mpath))["rows"] if os.path.exists(mpath) else []
gpu_ok = lambda r: not r.get("gpu_mismatch") and "gpu_error" not in r
cnt = lambda rs, v: sum(r["verdict"] == v for r in rs)


def why(r):
    if r["verdict"] in ("unsupported", "unknown") and r.get("reasons"):
        return r["reasons"][0][:90].replace("|", "/")
    return ""


out = ["# M5 with the M4 classes (NVIDIA A10G)", "",
       "Generated by `report4.py`. The 14 kernels in `kernels/` are CUDA C the agent (Claude, an LLM)",
       "wrote in one pass from the task text in `tasks.json`, before any of them was checked, and",
       "compiled with nvcc 13.2 -O3 -arch=sm_86 --ptx; the PTX is what is checked. The specs (register",
       "roles at each barrier) were written by reading that PTX. None was written to fit the tactics;",
       "two follow patterns from old CUDA samples (`r_interleaved`, `r_warp`) and one a common pattern",
       "(`r_earlyret`, an early return before `__syncthreads`). No defect was planted.", "",
       "| | kernels | proved | refuted | unknown | unsupported |", "|---|---|---|---|---|---|"]
fr = list(first.values())
out.append(f"| first run | {len(fr)} | {cnt(fr,'proved')} | {cnt(fr,'refuted')} | {cnt(fr,'unknown')} | {cnt(fr,'unsupported')} |")
out.append(f"| after the fixes the first run prompted | {len(rows)} | {cnt(rows,'proved')} | {cnt(rows,'refuted')} | {cnt(rows,'unknown')} | {cnt(rows,'unsupported')} |")
pr = [r for r in rows if r["verdict"] == "proved"]
lt = sorted(r["lean_seconds"] for r in pr if r.get("lean_seconds"))
rt = sorted(r["refutation_seconds"] for r in rows if r.get("refutation_seconds"))
out += ["",
        f"- Lean proof time per proved kernel: median {st.median(lt):.1f} s, max {lt[-1]:.1f} s (one Lean thread)." if lt else "",
        f"- Lean refutation replay: median {st.median(rt):.1f} s, max {rt[-1]:.1f} s." if rt else "",
        f"- GPU test of proved kernels against the class result: {sum(gpu_ok(r) for r in pr)} of {len(pr)} agree.",
        "- No speed is reported: every kernel is nvcc's own output, so an nvcc baseline is the same code.",
        "", "| kernel | first run | now | counterexample | proof attempt s | GPU test | note |", "|---|---|---|---|---|---|---|"]
for r in rows:
    f = first.get(r["name"], {})
    note = tasks[r["name"]].get("pattern", "") or why(r)
    out.append(f"| {r['name']} | {f.get('verdict', '')} | {r['verdict']} | {r.get('counterexample') or ''} | "
               f"{r.get('lean_seconds') or ''} | {'agrees' if gpu_ok(r) else 'disagrees'} | {note} |")
out += ["", "## After the run: supplied proofs and the accum class", "",
        "The table above is what the automation did. Two of its unsupported kernels were proved later:",
        "",
        "- `a_direct`: `proofs/a_direct.lean`, a supplied proof of `Reduce32.Atomic.Correct` (the statement",
        "  `specs/a_direct.json` generates), checked by `e5r ptx check --proof`. With",
        "  `specs/a_direct_accum.json` the `accum` class proves it with no supplied proof (13 s). That class",
        "  was built after this kernel was seen, so it is not an independent test of the class.",
        "- `s_pingpong`: `proofs/s_pingpong.lean`, a supplied proof of `Scan32.Correct`.",
        "", "`../../proofs/controls.sh` reruns both and the ten negative controls."]
if muts:
    out += ["", "## Random mechanical mutants", "",
            "`mutate.py 24 20261101` drew 24 mutants of `r_div2`, `a_tree` and `s_hs` (replace a register,",
            "flip a comparison, change an immediate, delete an instruction) that ptxas assembles; nobody",
            "chose them. The GPU test says which of them really changed the result on the launches it tries.",
            "Two never finish on the GPU (a loop whose counter no longer changes); non-termination has no",
            "finite counterexample, so they are `unknown`. `mut10` (every thread stores the block result)",
            "gives the right answer on the GPU and is refuted as a race: same-value stores by different",
            "threads in one phase are a data race under the PTX memory model.", "",
            "| | mutants | proved | refuted | unknown | unsupported |", "|---|---|---|---|---|---|"]
    wrong = [m for m in muts if not gpu_ok(m)]
    same = [m for m in muts if gpu_ok(m)]
    for lab, ms in (("wrong on the GPU", wrong), ("agree with the spec on the GPU", same)):
        out.append(f"| {lab} | {len(ms)} | {cnt(ms,'proved')} | {cnt(ms,'refuted')} | {cnt(ms,'unknown')} | {cnt(ms,'unsupported')} |")
    out += ["", "| mutant | change | verdict | counterexample | GPU test |", "|---|---|---|---|---|"]
    for m in muts:
        out.append(f"| {m['name']} | {m['change'].replace('|', '/')} | {m['verdict']} | {m.get('counterexample') or ''} | "
                   f"{'agrees' if gpu_ok(m) else 'disagrees'} |")
open(os.path.join(here, "RESULTS.md"), "w").write("\n".join(l for l in out if l is not None) + "\n")
print("\n".join(out[:14]))
