#!/usr/bin/env python3
"""Write a Lean module holding an ELF file packed for Theories/RamElf.lean:

    def elf : E5R.RamElf.File := ⟨len, [w0, w1, ...]⟩

word i = sum over k < 64 of byte(64 i + k) * 256^k, for the bytes that exist
(the last word is short). This is the packing rule agreed with the RAM-image
exporter (exporter-coordination.md); its output must be identical.

usage: pack_elf.py ELF OUT.lean NAMESPACE"""
import hashlib
import sys

elf, out, ns = sys.argv[1:4]
b = open(elf, 'rb').read()
words = [str(int.from_bytes(b[k:k + 64], 'little')) for k in range(0, len(b), 64)]
open(out, 'w').write(
    f'-- Generated by tools/pack_elf.py from an ELF with sha256 {hashlib.sha256(b).hexdigest()}; do not edit.\n'
    'import Theories.RamElf\nset_option maxRecDepth 100000\n'
    f'namespace {ns}\n'
    f'def elf : E5R.RamElf.File := ⟨{len(b)}, [{", ".join(words)}]⟩\n'
    f'end {ns}\n')
print(f'{out}: {len(b)} bytes, {len(words)} words, sha256 {hashlib.sha256(b).hexdigest()}')
