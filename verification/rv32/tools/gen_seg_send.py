    for o in reversed(opens):
        depth, i = 0, o
        while True:
            if body[i] == '(':
                depth += 1
            elif body[i] == ')':
                depth -= 1
                if depth == 0:
                    break
            i += 1
        ops.append(body[i + 2:].split(' ', 1)[0])
    lem = {'wr': 'Core.sameCsr_wr _ _ _ _', 'goto': 'Core.sameCsr_goto _ _'}
    term = f'({lem[ops[0]]})'
    for op in ops[1:]:
        term = f'(({lem[op]}).trans {term})'
    return term


