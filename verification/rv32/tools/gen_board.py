#!/usr/bin/env python3
"""Generate the Lean board description from its machine-readable JSON.

The JSON is the source of truth; the checker regenerates the Lean file and
refuses to continue if the committed copy differs."""
import json
import re
import sys
from pathlib import Path

VERIFY = Path(__file__).resolve().parents[1]


def camel(board_id):
    return ''.join(p.capitalize() for p in re.split(r'[^a-zA-Z0-9]', board_id) if p)


def render(board):
    ram = [m for m in board['memory'] if m['kind'] == 'ram']
    if len(ram) != 1:
        raise SystemExit('a board needs exactly one RAM region')
    in_ram = board.get('image_placement', 'flash') == 'ram'
    flash = [m for m in board['memory'] if m['kind'] == 'image']
    if len(flash) != (0 if in_ram else 1):
        raise SystemExit('a flash board needs exactly one image (flash) window; a RAM-image board none')
    addrs = [int(d['addr'], 16) for d in board['devices']]
    widths = [int(d.get('width', 4)) for d in board['devices']]
    if len(set(addrs)) != len(addrs) or any(w not in (1, 2, 4) or a % w for a, w in zip(addrs, widths)):
        raise SystemExit('device registers must be distinct, of width 1, 2 or 4, and aligned to it')
    ns = camel(board['id'])
    lines = [
        f'-- Generated by tools/gen_board.py from boards/{board["id"]}.json; do not edit.',
        'import Theories.Platform',
        f'namespace E5R.{ns}',
    ]
    if in_ram:
        # The image's read-only segments sit at the bottom of DRAM and are the
        # immutable image; model RAM starts at the image's `rwBase`.
        base, size = int(ram[0]['base'], 16), int(ram[0]['size'], 16)
        lines += [
            f'def dramBase : Nat := {base:#x}',
            f'def dramEnd : Nat := {base + size:#x}',
            'def board (rwBase : Nat) : Board where',
            '  ramBase := rwBase',
            '  ramSize := dramEnd - rwBase',
            '  devices := [',
        ]
    else:
        lines += [
            f'def flashBase : Nat := {int(flash[0]["base"], 16):#x}',
            f'def flashSize : Nat := {int(flash[0]["size"], 16):#x}',
            'def board : Board where',
            f'  ramBase := {int(ram[0]["base"], 16):#x}',
            f'  ramSize := {int(ram[0]["size"], 16):#x}',
            '  devices := [',
        ]
    for i, d in enumerate(board['devices']):
        sep = ',' if i + 1 < len(board['devices']) else ''
        # `width` (bytes per access) defaults to a word register.
        lines.append(f'    ⟨{int(d["addr"], 16):#010x}, "{d["name"]}", '
                     f'{str(d["read"]).lower()}, {str(d["write"]).lower()}, {int(d.get("width", 4))}⟩{sep}')
    lines += ['  ]', f'end E5R.{ns}', '']
    return '\n'.join(lines)


def main():
    args = sys.argv[1:]
    check = '--check' in args
    args = [a for a in args if a != '--check']
    paths = args or sorted((VERIFY / 'boards').glob('*.json'))
    for p in map(Path, paths):
        board = json.loads(p.read_text())
        if board.get('schema') != 'e5r.board.v1':
            raise SystemExit(f'{p}: unknown schema')
        out = VERIFY / 'Theories' / 'Board' / f'{camel(board["id"])}.lean'
        text = render(board)
        if check:
            # Refuse a committed Lean board that no longer matches its JSON.
            if not out.exists() or out.read_text() != text:
                raise SystemExit(f'{out.relative_to(VERIFY)} differs from {p.name}; run tools/gen_board.py')
        else:
            out.write_text(text)
            print(out.relative_to(VERIFY))


if __name__ == '__main__':
    main()
