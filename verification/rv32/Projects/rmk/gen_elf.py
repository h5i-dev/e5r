#!/usr/bin/env python3
"""Write Elf.lean: the pinned RMK ELF as an `E5R.RamElf.File` (temporary,
until the exporter's image module is wired into the job runner).

Original e5r code, Apache-2.0. Packing rule (main, exporter-coordination.md):
word i = sum_{k<64} byte(64i+k) * 256^k over the bytes that exist; decimal
literals. The ELF's sha256 is checked against the pin first.
Usage: gen_elf.py ELF [OUT]
"""
import hashlib
import sys
from pathlib import Path

PIN = 'f39d833f520ba4de6c7085423a8dc3ee475ec19bdfb55c10c81c6ae868f43c30'

elf = Path(sys.argv[1]).read_bytes()
digest = hashlib.sha256(elf).hexdigest()
if digest != PIN:
    sys.exit(f'ELF sha256 {digest} is not the pin {PIN}')
words = [int.from_bytes(elf[i:i + 64], 'little') for i in range(0, len(elf), 64)]
out = Path(sys.argv[2] if len(sys.argv) > 2 else Path(__file__).with_name('Elf.lean'))
with open(out, 'w') as f:
    f.write('-- Generated by Projects/rmk/gen_elf.py; do not edit.\n')
    f.write(f'-- rmk-qemu-riscv, ELF sha256 {digest}, {len(elf)} bytes, {len(words)} words.\n')
    f.write('import Theories.RamElf\n\nset_option maxRecDepth 100000\n\nnamespace E5R.Rmk.Image\n\n')
    f.write(f'def elf : E5R.RamElf.File := ⟨{len(elf)}, [\n')
    f.write(',\n'.join(str(w) for w in words))
    f.write(']⟩\n\nend E5R.Rmk.Image\n')
print(f'{out}: {len(words)} words')
