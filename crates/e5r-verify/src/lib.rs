//! Strict research export of an ELF32 RV32I loaded image to Lean source.
//!
//! No disassembly, CFG or decompiler facts enter the proof subject.
#![forbid(unsafe_code)]

use e5r_core::{Arch, Bits, Endian};
use e5r_format::{LoadOptions, Object};
use std::fmt::Write;

/// Reject containers outside the small, static, relocation-free research contract.
pub fn load_image(bytes: &[u8]) -> Result<Object, String> {
    if bytes.len() > 65536 || bytes.len() < 52 {
        return Err("ELF must be between 52 and 65536 bytes".into());
    }
    if &bytes[..7] != b"\x7fELF\x01\x01\x01"
        || bytes[16..20] != [2, 0, 243, 0]
        || bytes[36..40] != [0; 4]
    {
        return Err("requires static little-endian ELF32 EM_RISCV ET_EXEC, e_flags=0".into());
    }
    // Refuse dynamic/interpreter/TLS segments and any relocation section, even
    // if the generic analysis loader could inspect them without applying them.
    let u16at = |n| u16::from_le_bytes([bytes[n], bytes[n + 1]]) as usize;
    let u32at = |n| {
        bytes
            .get(n..n + 4)
            .map(|b| u32::from_le_bytes(b.try_into().unwrap()) as usize)
            .ok_or_else(|| "truncated program headers".to_string())
    };
    if u16at(40) != 52 || u16at(42) != 32 || !(1..=16).contains(&u16at(44)) {
        return Err("requires at most 16 ELF32 program headers".into());
    }
    let mut mapped_bytes = 0;
    let mut loads = 0;
    for i in 0..u16at(44) {
        let off = u32at(28)? + i * 32;
        // Bound and validate every full header before invoking the generic
        // analysis loader, which deliberately tolerates more ELF variants.
        let header = bytes
            .get(off..off + 32)
            .ok_or("truncated program headers")?;
        let field = |n| u32::from_le_bytes(header[n..n + 4].try_into().unwrap()) as u64;
        match field(0) {
            0 | 0x6474e551 => {}
            1 => {
                let file = field(4);
                let base = field(8);
                let filesz = field(16);
                let memsz = field(20);
                let flags = field(24);
                mapped_bytes += memsz;
                loads += 1;
                if memsz == 0
                    || filesz > memsz
                    || mapped_bytes > 65536
                    || file + filesz > bytes.len() as u64
                    || base + memsz > (1u64 << 32)
                    || flags > 7
                    || flags & 3 == 3
                {
                    return Err("unsupported PT_LOAD bounds or permissions".into());
                }
            }
            _ => return Err("unsupported program header".into()),
        }
    }
    if loads == 0 {
        return Err("requires a PT_LOAD image".into());
    }
    let obj = e5r_format::load(bytes, &LoadOptions::default()).map_err(|e| e.to_string())?;
    if obj.bits != Bits::Bits32
        || obj.endian != Endian::Little
        || obj.arch != Arch::Sleigh("RISCV:LE:32:default".into())
        || !obj.warnings.is_empty()
        || obj.pic
        || !obj.imports.is_empty()
    {
        return Err("unsupported image metadata or loader warnings".into());
    }
    if obj.sections.iter().any(|s| matches!(s.kind, 4 | 6 | 9)) {
        return Err("dynamic or relocation sections are unsupported".into());
    }
    let mut end = 0;
    let mut total = 0;
    for s in obj.memory.segments() {
        let start = s.range.start().get();
        total += s.range.len();
        if s.range.is_empty()
            || start < end
            || s.range.end().get() > (1u64 << 32)
            || total > 65536
            || (s.perms.exec && s.perms.write)
        {
            return Err(
                "empty, overlapping, oversized, out-of-RV32 or writable-executable map".into(),
            );
        }
        end = s.range.end().get();
    }
    let entry = obj.entry.ok_or("missing entry")?;
    if entry.get() % 4 != 0 || !obj.memory.is_executable(entry) {
        return Err("entry must be aligned executable memory".into());
    }
    Ok(obj)
}

fn list(bytes: &[u8]) -> String {
    format!("{:?}", bytes)
}

/// Export original file bytes, loaded bytes/permissions and segment provenance.
/// The Lean loader equality theorem checks their correspondence independently.
pub fn export(bytes: &[u8]) -> Result<String, String> {
    let obj = load_image(bytes)?;
    let mut out = String::from(
        "-- Generated by e5r-verify; regenerate, do not edit.\nimport Theories.RV32\nnamespace Exported\n",
    );
    writeln!(out, "def elfBytes : List Nat := {}", list(bytes)).unwrap();
    writeln!(out, "def entry : Nat := {}", obj.entry.unwrap().get()).unwrap();
    out.push_str("def image : List RV32.Region := [\n");
    for (i, s) in obj.memory.segments().iter().enumerate() {
        if i != 0 {
            out.push_str(",\n");
        }
        writeln!(
            out,
            "-- PT_LOAD file offset {}, file size {}, memory size {}; ELF permissions",
            s.file_offset,
            s.file_len(),
            s.range.len()
        )
        .unwrap();
        write!(
            out,
            "  ⟨{}, {}, {}, {}, {}⟩",
            s.range.start().get(),
            list(&s.read(s.range.start(), s.range.len()).unwrap()),
            s.perms.read,
            s.perms.write,
            s.perms.exec
        )
        .unwrap();
    }
    out.push_str("\n]\nend Exported\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture() -> Vec<u8> {
        let mut b = vec![0u8; 128];
        b[..7].copy_from_slice(b"\x7fELF\x01\x01\x01");
        for (off, value) in [(16, 2u16), (18, 243), (40, 52), (42, 32), (44, 1), (46, 40)] {
            b[off..off + 2].copy_from_slice(&value.to_le_bytes());
        }
        for (off, value) in [
            (20, 1u32),
            (24, 4096),
            (28, 52),
            (52, 1),
            (56, 124),
            (60, 4096),
            (64, 4096),
            (68, 4),
            (72, 8),
            (76, 5),
            (80, 4),
        ] {
            b[off..off + 4].copy_from_slice(&value.to_le_bytes());
        }
        b[124..].copy_from_slice(&0x00700513u32.to_le_bytes());
        b
    }

    #[test]
    fn exports_loaded_bytes_zero_fill_permissions_and_source() {
        let bytes = fixture();
        let image = load_image(&bytes).unwrap();
        assert_eq!(
            image.memory.read(e5r_core::Addr(4096), 8).unwrap(),
            [19, 5, 112, 0, 0, 0, 0, 0]
        );
        let source = export(&bytes).unwrap();
        assert!(source.contains("⟨4096, [19, 5, 112, 0, 0, 0, 0, 0], true, false, true⟩"));
        assert!(source.contains("PT_LOAD file offset 124, file size 4, memory size 8"));
        assert!(source.contains(&format!("def elfBytes : List Nat := {bytes:?}")));
        assert_eq!(source, export(&bytes).unwrap());
    }

    #[test]
    fn declines_ambiguous_and_unsupported_images() {
        for (offset, value) in [
            (18, 62),
            (36, 1),
            (16, 3),
            (76, 7),
            (52, 2),
            (24, 1),
            (72, 3),
            (72, 0),
            (76, 8),
            (44, 0),
            (40, 0),
        ] {
            let mut bytes = fixture();
            bytes[offset] = value;
            assert!(load_image(&bytes).is_err(), "accepted mutation at {offset}");
        }
        let bytes = fixture();
        for end in 0..bytes.len() {
            assert!(
                load_image(&bytes[..end]).is_err(),
                "accepted truncation at {end}"
            );
        }
    }

    #[test]
    fn rejects_overlaps_oversized_and_out_of_rv32_maps() {
        let mut overlap = fixture();
        overlap[44..46].copy_from_slice(&2u16.to_le_bytes());
        let header = overlap[52..84].to_vec();
        overlap[84..116].copy_from_slice(&header);
        assert!(load_image(&overlap).is_err());
        let mut large = fixture();
        large[72..76].copy_from_slice(&65537u32.to_le_bytes());
        assert!(load_image(&large).is_err());
        let mut outside = fixture();
        outside[60..64].copy_from_slice(&0xfffffffcu32.to_le_bytes());
        assert!(load_image(&outside).is_err());
    }

    #[test]
    fn malformed_and_wrong_arch_are_errors() {
        for b in [vec![], vec![0; 52], b"\x7fELF".to_vec()] {
            assert!(load_image(&b).is_err());
        }
    }
}
