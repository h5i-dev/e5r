"""Write bench/swe-bin/SUMMARY.md from tasks/*.json: kept/dropped counts by reason, and one row
per task. Usage: summary.py [DATASET.jsonl] (the dataset gives the 73 task ids, so a task that
has no JSON yet shows as "not converted")."""

from __future__ import annotations

import collections
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BENCH = os.path.dirname(HERE)
TASKS = os.path.join(BENCH, "tasks")
SWB = os.environ.get("SWB", "/mnt/scratch/ec2-user/swe-bin")
DATASET = sys.argv[1] if len(sys.argv) > 1 else os.path.join(SWB, "dl", "cr.jsonl")
C_REPOS = {"jqlang/jq", "redis/redis", "valkey-io/valkey", "micropython/micropython"}


def reason_class(r: str) -> str:
    r = re.sub(r"^(FAIL_TO_PASS|PASS_TO_PASS) .*?: ", r"\1 test: ", r)
    return re.sub(r" \d+.*$", "", r)


def main():
    ids = [json.loads(line) for line in open(DATASET)]
    npath = os.path.join(TASKS, "notes.json")
    notes = json.load(open(npath)) if os.path.exists(npath) else {}
    rows, reasons = [], collections.Counter()
    by = collections.Counter()
    for t in ids:
        iid, repo = t["instance_id"], t["repo"]
        lang = "C" if repo in C_REPOS else "Rust"
        p = os.path.join(TASKS, f"{iid}.json")
        if iid == "notes":
            continue
        if not os.path.exists(p):
            by[(lang, "not converted")] += 1
            rows.append((iid, lang, "not converted", "", "", "", "", "", ""))
            continue
        r = json.load(open(p))
        st = r["status"]
        by[(lang, st)] += 1
        if st != "kept":
            for x in r.get("drop_reason", []):
                reasons[(lang, reason_class(x))] += 1
            why = "; ".join(r.get("drop_reason", []))[:140]
            if iid in notes:
                why += " (" + notes[iid][:160] + ")"
            rows.append((iid, lang, "dropped", why, "", "", "", "", ""))
            continue
        bs = r["binaries"]
        size = " + ".join(f"{b['base']['bytes'] / 1e6:.1f} MB" for b in bs)
        insns = " + ".join(f"{b['base']['instructions']:,}" for b in bs)
        lv = collections.Counter()
        for b in bs:
            for k, v in b["base"]["levels"].items():
                if isinstance(v, int):
                    lv[k] += v
                else:
                    lv["check error"] += 1
        levels = ", ".join(f"{k} {lv[k]}" for k in ("L2", "L1", "L0", "below L0", "check error") if lv.get(k))
        byte = sum(len(b["gold_changes"]["modified"]) + len(b["gold_changes"]["added"]) for b in bs)
        src = sorted({n for b in bs for n in b.get("source_changes", {}).get("base", []) + b.get("source_changes", {}).get("gold", [])})
        sc = sum(b["scratch"]["instructions"] for b in bs)
        tests = f"{sum(x['kind'] == 'FAIL_TO_PASS' for x in r['tests'])}/{sum(x['kind'] == 'PASS_TO_PASS' for x in r['tests'])}"
        if r.get("excluded_tests"):
            tests += f" (+{len(r['excluded_tests'])} excl.)"
        rows.append((iid, lang, "kept", tests, size, insns, levels, f"{byte} / {', '.join(src)[:80] or '-'}", f"{sc:,}"))
    out = ["# swe-bin: converted tasks", "",
           "Generated by `convert/summary.py` from `tasks/*.json`. Patch mode is the SWE-bench port; scratch mode is",
           "SWE-bench-derived (function-level from-scratch), not SWE-bench.", "",
           "## Counts", "", "| language | kept | dropped | not converted | total |", "| --- | --- | --- | --- | --- |"]
    for lang in ("C", "Rust"):
        k, d, n = by[(lang, "kept")], by[(lang, "dropped")], by[(lang, "not converted")]
        out.append(f"| {lang} | {k} | {d} | {n} | {k + d + n} |")
    out += ["", "## Drop reasons", "", "| language | reason | tasks |", "| --- | --- | --- |"]
    for (lang, why), c in sorted(reasons.items()):
        out.append(f"| {lang} | {why} | {c} |")
    out += ["", "## Tasks", "",
            "Tests: FAIL_TO_PASS/PASS_TO_PASS kept (excluded: tests that do not run a subject, see the JSON). Changed: "
            "byte-level count / source-level functions. Scratch: base instructions scratch mode removes.", "",
            "| task | lang | status | tests or reason | size | instructions | profile levels | changed | scratch |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for row in rows:
        out.append("| " + " | ".join(str(x).replace("|", "/") for x in row) + " |")
    with open(os.path.join(BENCH, "SUMMARY.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out[:20]))


if __name__ == "__main__":
    main()
