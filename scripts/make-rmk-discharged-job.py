#!/usr/bin/env python3
"""Generate the DISCHARGED Deframer/receive-step job once a proof of main's `CopyContract` exists.

Usage: python3 -I scripts/make-rmk-discharged-job.py BRIDGE_MODULE BRIDGE_THEOREM

  BRIDGE_MODULE   e.g. Projects.rmk.Deframer.CopyDischarge (main's, imports the memmove chain)
  BRIDGE_THEOREM  e.g. E5R.Rmk.Deframer.copy_contract, of type exactly `CopyContract`

Writes verification/rv32/Projects/ramimage/SessionDischarged.lean (the runner wrapper: every Deframer
method and both session steps with the hypothesis REMOVED, by applying the bridge) and
verification/rv32/jobs/rmk/rmk-session-discharged.json, whose module list is the import closure
of the wrapper in dependency order (the runner checks every one from source; model, board and
generated image modules excluded, as the runner adds them). The conditional jobs and their
receipts are left as they are. Lean decides whether the bridge has the stated type: if it does
not, the wrapper fails to check and the job reports `failed`.
"""
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "verification", "rv32")
RUNNER = {"Theories.Hart", "Theories.Platform", "Theories.Logic", "Theories.FlashElf", "Theories.RamElf",
          "Projects.rmk.Elf", "Projects.rmk.ElfFidelity"}
mod, thm = sys.argv[1], sys.argv[2]
assert re.fullmatch(r"[A-Za-z0-9_.]+", mod) and re.fullmatch(r"[A-Za-z0-9_.]+", thm), "plain names only"

WRAP = f'''/-
  RMK Deframer methods and Rynk session steps with memmove's `CopyContract` DISCHARGED by
  `{thm}` ({mod}), on the image the job runner generates
  (`jobs/rmk/rmk-session-discharged.json`; generated by scripts/make-rmk-discharged-job.py).
  Original e5r code, Apache-2.0.

  NOT `SessionSafe`. What is not covered: the path 0x80003e70 -> 0x80003fd8 (dispatch, encode,
  UART send, yields), the path 0x80003f7c -> loop head (UART read future, executor), poll entry
  and exit, other tasks, and interrupts (`Quiet` is a precondition at every step). See
  verification/rv32/rmk-audit/SESSION-BOUNDARY.md. Image and board: `E5R.RmkDeframer.img_eq`,
  `board_eq`.
-/
import Projects.ramimage.Session
import {mod}

namespace E5R.RmkSessionDischarged
open E5R E5R.Rmk.Deframer E5R.Rmk.Deframer.Session
open E5R.Rmk (QRun)

theorem copy : CopyContract := {thm}

/-- The four Deframer contracts, no hypothesis. -/
theorem deframer : TailContract tailStack ∧ ParkContract ∧ UnparkContract ∧ NextContract :=
  ⟨Tail.tail_from_copy copy, Park.park_from_copy copy, Unpark.unpark_from_copy copy, next_from_copy copy⟩

/-- The receive step from the session loop head, no hypothesis. -/
theorem recv (m₀ : Machine) (h : SessPre m₀) : ∃ k m, QRun B img k m₀ m ∧ RecvOut m₀ m :=
  recv_step copy m₀ h

/-- The unpark call site back to the loop head, no hypothesis. -/
theorem unpark (m₀ : Machine) (h : UnparkAt m₀) :
    ∃ k m, QRun B img k m₀ m ∧ SessPre m ∧ m.core.get 2 = m₀.core.get 2 ∧
      filled m.ram dfr = (ramRead m₀.ram 0x8002a798 .w).toNat :=
  E5R.RmkSession.unpark_conditional copy m₀ h

/-- Unpark, loop head, receive, as one quiet run, no hypothesis. -/
theorem unpark_then_recv (m₀ : Machine) (h : UnparkAt m₀) :
    ∃ k m₁ m, QRun B img k m₀ m ∧ SessPre m₁ ∧ RecvOut m₁ m ∧ m.core.get 2 = m₀.core.get 2 :=
  E5R.RmkSession.unpark_then_recv copy m₀ h

end E5R.RmkSessionDischarged
'''
wpath = os.path.join(ROOT, "Projects/ramimage/SessionDischarged.lean")
open(wpath, "w", encoding="utf-8").write(WRAP)

order = []
def visit(m, stack=()):
    if m in order or m in RUNNER or m.startswith("Theories.Board."):
        return
    assert m not in stack, f"import cycle at {m}"
    p = os.path.join(ROOT, m.replace(".", "/") + ".lean")
    assert os.path.exists(p), f"missing module {m} ({p})"
    for i in re.findall(r"^import (\S+)", open(p, encoding="utf-8").read(), re.M):
        visit(i, stack + (m,))
    order.append(m)
visit("Projects.ramimage.SessionDischarged")

# every theorem the bridge file itself declares (main's discharged contracts), fully qualified
bsrc = open(os.path.join(ROOT, mod.replace(".", "/") + ".lean"), encoding="utf-8").read()
bns = re.search(r"^namespace (\S+)", bsrc, re.M)
bthms = [f"{bns.group(1)}.{n}" if bns else n for n in re.findall(r"^theorem (\S+)", bsrc, re.M)]

base = json.load(open(os.path.join(ROOT, "jobs/rmk/rmk-session-conditional.json")))
job = dict(base)
job["id"] = "rmk-session-discharged"
job["modules"] = [m.replace(".", "/") + ".lean" for m in order]
job["theorems"] = list(dict.fromkeys([thm] + bthms)) + ["E5R.RmkSessionDischarged.*", "E5R.Rmk.Deframer.Session.recv_step",
                   "E5R.Rmk.Deframer.Session.unpark_step", "E5R.Rmk.Deframer.cobs_report",
                   "E5R.RmkDeframer.img_eq", "E5R.RmkDeframer.board_eq"]
job["symbols"] = dict(base["symbols"], **{"0x80020c1e": "memmove"})
jpath = os.path.join(ROOT, "jobs/rmk/rmk-session-discharged.json")
json.dump(job, open(jpath, "w"), indent=2)
open(jpath, "a").write("\n")
print(f"wrote {wpath}\nwrote {jpath} ({len(order)} modules)")
