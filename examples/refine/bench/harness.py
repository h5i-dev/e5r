#!/usr/bin/env python3
"""The refinement benchmark harness (spec-v1-refine.md 9'; examples/refine/bench/README.md).

    harness.py list
    harness.py prepare TASK --baseline SHA [--root DIR]   make the task's workdir
    harness.py check   WORKDIR                            what the solver runs; also the verdict
    harness.py run     TASK --baseline SHA [--root DIR] [--timeout MIN]
    harness.py collect TASK [--root DIR]                  tokens, turns, time, outcome, speed-up

A task gives a solver one function A of a rustc-compiled binary (in the
structured text, `A.s`), asks for a faster B by editing that function's text
(`B.s`), and a Lean proof that B refines A (`lean/Task/Proof.lean`). The
verdict is the harness's, never the solver's:

  proved   B assembles and links, B agrees with A on every workload in the
           simulator, the diff certificate is generated, and the proof checks
           against the FIXED statement in lean/Task/Statement.lean with only
           the standard axioms (or the bv_decide tier, recorded as such);
  refuted  B differs from A on a workload (output or exit status): B is wrong;
  unknown  anything else (no B, no proof, a proof that does not check).

Rules it enforces (v1-common.md, the benchmark updates):

* NO SESSION BEFORE THE FREEZE: `run` refuses unless --baseline is an
  ancestor of origin/main and NOCOMPILER_BENCH_FROZEN equals it (the lead
  sets it when the freeze is announced). `prepare` and `check` are allowed,
  for smoke tests without a solver.
* Isolation: one fresh workdir per task under --root (default
  /mnt/scratch/ec2-user/bench/work), containing only the task, the tools
  and a snapshot of the repository at the baseline (`git archive`); other
  tasks' material is not in it, and the harness's own files are chmod 000
  while a session runs.
* Transcripts: before a session, ~/.claude/projects/<cwd-with-dashes> is made
  a symlink to /mnt/scratch/ec2-user/bench-logs/<task> (the root disk is
  nearly full), and the harness checks the transcript lands there.
* At most 2 sessions at a time (a lock directory), Lean capped at 4 GB.
* Tokens: the sum of the `usage` fields (input, output, cache read and
  creation) of the assistant messages in the session's .jsonl; also turns
  and wall time.
"""
import glob, hashlib, json, os, shutil, subprocess, sys, time

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../.."))
BENCH = os.path.join(REPO, "examples/refine/bench")
ROOT = "/mnt/scratch/ec2-user/bench/work"
LOGS = "/mnt/scratch/ec2-user/bench-logs"
LOCKS = "/mnt/scratch/ec2-user/bench/locks"
MAX_SESSIONS = 2


def tasks():
    return {t["id"]: t for t in json.load(open(os.path.join(BENCH, "tasks.json")))["tasks"]}


def manifest():
    return json.load(open(os.path.join(BENCH, "manifest.json")))


def sh(*c, cwd=None, check=True, **k):
    r = subprocess.run(c, cwd=cwd, capture_output=True, text=True, **k)
    if check and r.returncode:
        sys.exit(f"{' '.join(map(str, c))}: {r.stderr[-2000:]}")
    return r


def arg(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default


STATEMENT = """import Task.ImageA
import Task.ImageB
import NoCompiler

/- The statement a solution must prove, exactly (the harness checks
   `Task.refines` against it). B refines A for every specification: wherever
   A runs safely and terminates, B does, touches only what A may touch, and
   ends as A does (docs/isa/refine.md). -/
namespace Task
open NoCompiler

abbrev Statement : Prop :=
  ∀ {α : Type} (sp : Spec α), Refines sp ImageA.code ImageA.{f}_dom ImageA.{f}_entry
    ImageB.code ImageB.{f}_dom ImageB.{f}_entry

end Task
"""

CHECK = """import Task.Statement
import Task.Proof

/- Generated by the harness: the solution's theorem has the fixed statement. -/
example : Task.Statement := @Task.refines
"""


def task_md(t, m):
    return f"""# Task {t['id']}

Make one function of a rustc-compiled RISC-V binary faster, and prove that the
faster version refines the original.

* The binary: `A.elf` (rustc opt-level 3 into the nocompiler profile; see
  docs/isa/refine-targets.md). Its structured text: `A.s` (docs/isa/asm.md).
* The function: `{m['symbol']}`: {t['what']}.
* What to do: {t['goal']}
* Write `B.s`: a copy of `A.s` in which only that function's body is changed.
  Nothing else may change (the harness rejects changes to other functions).
* Prove, in `lean/Task/Proof.lean`, a theorem `Task.refines : Task.Statement`
  (lean/Task/Statement.lean, fixed): B refines A, for every specification.
  `./check.sh` builds B, exports both images, writes the diff certificate
  (`lean/Task/Diff.lean`, from `nocompiler refine`) and checks your proof. The
  tools are documented in docs/isa/refine.md (`nocompiler_refine`,
  `RRegion.ok_of_seqEquiv`, `seq_equiv`, `seq_equiv_bv`).
* B is measured on the workloads in `workloads/` with `nocompiler sim`
  (simulated in-order core): instructions and cycles inside the function. A
  B that differs from A on any workload is refuted.
* No `sorry`, no `native_decide`, no new axioms. `bv_decide` is allowed and
  recorded as the bv_decide trust tier.
"""


CHECK_SH = r"""#!/usr/bin/env bash
# Build B from B.s, compare it with A on the workloads, and check the proof.
set -uo pipefail
cd "$(dirname "$0")"
N=./tools/nocompiler
f=$(cat FUNCTION)
fail() { echo "CHECK: $1"; exit 1; }
[ -f B.s ] || fail "no B.s"
$N asm B.s -o B.o >/dev/null || fail "B.s does not assemble"
ld.lld -static -e "$(cat DRIVER)" --build-id=none -z noseparate-code \
  --section-start=.text="$(cat TEXT_START)" --symbol-ordering-file=ORDER B.o -o B.elf 2>ld.err || fail "B does not link: $(cat ld.err)"
# Only the task's function may change.
python3 -I - <<'PY' || fail "a function other than the task's changed"
import subprocess, sys
f = open("FUNCTION").read().strip()
def funcs(e):
    t = subprocess.run(["./tools/nocompiler", "disasm", e], capture_output=True, text=True).stdout
    out, cur = {}, None
    for l in t.splitlines():
        if l.startswith("func "):
            cur = l.split()[1]; out[cur] = []
        elif cur and l.strip() and not l.strip().startswith(";"):
            out[cur].append(l.split(";")[0].rstrip())
    return out
a, b = funcs("A.elf"), funcs("B.elf")
sys.exit(0 if set(a) == set(b) and all(a[g] == b[g] for g in a if g != f) else 1)
PY
# A and B on the workloads.
for w in workloads/*.bin; do
  ra=$($N sim A.elf --stdin "$w" 2>/dev/null | od -An -tx1 | tr -d ' \n'); sa=${PIPESTATUS[0]}
  rb=$($N sim B.elf --stdin "$w" 2>/dev/null | od -An -tx1 | tr -d ' \n'); sb=${PIPESTATUS[0]}
  [ "$ra" = "$rb" ] && [ "$sa" = "$sb" ] || { echo "REFUTED: $w: A gives $ra ($sa), B gives $rb ($sb)"; exit 2; }
done
$N export B.elf --namespace Task.ImageB -o lean/Task/ImageB.lean 2>/dev/null || fail "export B"
$N refine A.elf B.elf "$f" --namespace Task.Diff -o lean/Task/Diff.lean || fail "no diff certificate"
[ -f lean/Task/Proof.lean ] || fail "no lean/Task/Proof.lean"
(cd lean && systemd-run --user --scope --quiet -p MemoryMax=4G -p MemorySwapMax=0 --setenv=PATH="$PATH" \
  --setenv=ELAN_HOME="${ELAN_HOME:-}" timeout 1800 lake env lean Task/Check.lean) >check.log 2>&1 \
  || fail "the proof does not check: $(tail -20 check.log)"
grep -q "sorry" check.log && fail "the proof uses sorry"
(cd lean && lake env lean --run Task/Axioms.lean) > axioms.log 2>&1 || fail "axioms: $(cat axioms.log)"
echo "PROVED ($(cat axioms.log))"
"""

AXIOMS = """import Task.Proof
open Lean in
/- The axioms of the solution: standard, or the bv_decide tier (docs/isa/trust.md). -/
def main : IO UInt32 := do
  let env ← importModules #[{ module := `Task.Proof }] {}
  let axs := ((Lean.CollectAxioms.collect `Task.refines).run env |>.run {}).2.axioms
  let std := [``propext, ``Classical.choice, ``Quot.sound]
  let native := axs.filter fun a => a == `Lean.ofReduceBool || a == `Lean.trustCompiler ||
    a.components.any (· == `_native)
  let other := axs.filter fun a => !std.contains a && !native.contains a
  if !other.isEmpty then
    IO.println s!"non-standard axioms {other}"; return 1
  IO.println (if native.isEmpty then "kernel tier" else "bv_decide tier")
  return 0
"""


def prepare(tid, baseline, root):
    t = tasks()[tid]
    m = manifest()[t["function"]]
    w = os.path.join(root, tid)
    if os.path.exists(w):
        shutil.rmtree(w)
    os.makedirs(w)
    # The repository at the baseline, without the benchmark's own material.
    arch = sh("git", "archive", "--format=tar", baseline, "lean", "docs", "crates", "Cargo.toml", "Cargo.lock",
              cwd=REPO, text=False).stdout if False else None
    tar = os.path.join(w, ".repo.tar")
    with open(tar, "wb") as fh:
        subprocess.run(["git", "archive", "--format=tar", baseline, "lean", "docs"], cwd=REPO, stdout=fh, check=True)
    sh("tar", "xf", tar, cwd=w)
    os.remove(tar)
    shutil.rmtree(os.path.join(w, "lean", "Examples"), ignore_errors=True)
    # The tools: the nocompiler binary built at the baseline (the caller's job;
    # here, the one in target/release, checked to come from that commit).
    os.makedirs(os.path.join(w, "tools"))
    shutil.copy(os.path.join(REPO, "target/release/nocompiler"), os.path.join(w, "tools/nocompiler"))
    elf = os.path.join(REPO, m["elf"])
    if hashlib.sha256(open(elf, "rb").read()).hexdigest() != m["sha256"]:
        sys.exit(f"{elf} is not the manifest's A")
    shutil.copy(elf, os.path.join(w, "A.elf"))
    N = os.path.join(w, "tools/nocompiler")
    open(os.path.join(w, "A.s"), "w").write(sh(N, "disasm", "A.elf", cwd=w).stdout)
    shutil.copy(os.path.join(w, "A.s"), os.path.join(w, "B.s"))
    for name, val in [("FUNCTION", m["symbol"]), ("DRIVER", m["driver"])]:
        open(os.path.join(w, name), "w").write(val + "\n")
    syms = sh("llvm-nm", "-n", "A.elf", cwd=w).stdout.split("\n")
    funcs = [l.split()[2] for l in syms if len(l.split()) == 3 and l.split()[1] in "Tt" and not l.split()[2].startswith(".")]
    open(os.path.join(w, "ORDER"), "w").write("".join(f + "\n" for f in funcs))
    text = [l for l in sh("llvm-readelf", "-S", "-W", "A.elf", cwd=w).stdout.splitlines() if " .text " in l][0]
    start = text.replace("[ ", "[").split()[3]
    open(os.path.join(w, "TEXT_START"), "w").write("0x" + start + "\n")
    # Lean: A's image, the fixed statement, the check, a proof stub.
    tl = os.path.join(w, "lean", "Task")
    os.makedirs(tl)
    sh(N, "export", "A.elf", "--namespace", "Task.ImageA", "-o", os.path.join(tl, "ImageA.lean"), cwd=w)
    from_lean = sh(N, "export", "A.elf", "--namespace", "X", cwd=w).stdout
    ident = next(l.split()[1][: -len("_entry")] for l in from_lean.splitlines()
                 if l.startswith("def ") and l.split()[1].endswith("_entry") and m["symbol"] in l + m["symbol"])
    open(os.path.join(tl, "Statement.lean"), "w").write(STATEMENT.replace("{f}", ident_of(from_lean, m["symbol"])))
    open(os.path.join(tl, "Check.lean"), "w").write(CHECK)
    open(os.path.join(tl, "Axioms.lean"), "w").write(AXIOMS)
    open(os.path.join(tl, "Proof.lean"), "w").write(
        "import Task.Statement\nimport Task.Diff\n\nnamespace Task\nopen NoCompiler\n\n"
        "theorem refines : Statement := by\n  sorry\n\nend Task\n")
    lake = open(os.path.join(w, "lean", "lakefile.toml")).read()
    open(os.path.join(w, "lean", "lakefile.toml"), "w").write(lake + '\n[[lean_lib]]\nname = "Task"\n')
    # Workloads.
    sh("python3", "-I", os.path.join(BENCH, "workloads.py"), t["function"], os.path.join(w, "workloads"))
    open(os.path.join(w, "TASK.md"), "w").write(task_md(t, m))
    open(os.path.join(w, "check.sh"), "w").write(CHECK_SH)
    os.chmod(os.path.join(w, "check.sh"), 0o755)
    json.dump({"task": tid, "baseline": baseline, "prepared": time.time()}, open(os.path.join(w, ".harness.json"), "w"))
    print(w)


def ident_of(lean, symbol):
    """The Lean identifier `nocompiler export` gives the function `symbol`."""
    for l in lean.splitlines():
        if l.startswith("/-- `") and symbol in l:
            pass
    # export writes `<id>_entry` for each conforming function in symbol order; match by the
    # `-- symbol` comment it puts before the entry definition.
    lines = lean.splitlines()
    for k, l in enumerate(lines):
        if l.startswith("def ") and l.split()[1].endswith("_entry"):
            ctx = "\n".join(lines[max(0, k - 12):k])
            if symbol in ctx:
                return l.split()[1][: -len("_entry")]
    sys.exit(f"no exported entry for {symbol}")


def frozen(baseline):
    env = os.environ.get("NOCOMPILER_BENCH_FROZEN")
    if env != baseline:
        sys.exit("refusing: the benchmark runs only after the freeze (set NOCOMPILER_BENCH_FROZEN to the "
                 "baseline main commit the lead announced)")
    sh("git", "fetch", "-q", "origin", cwd=REPO)
    if subprocess.run(["git", "merge-base", "--is-ancestor", baseline, "origin/main"], cwd=REPO).returncode:
        sys.exit(f"refusing: {baseline} is not on origin/main")


def project_dir(w):
    return os.path.expanduser("~/.claude/projects/" + os.path.realpath(w).replace("/", "-"))


def run(tid, baseline, root, timeout_min):
    frozen(baseline)
    w = os.path.join(root, tid)
    if not os.path.exists(w):
        sys.exit(f"prepare {tid} first")
    os.makedirs(LOCKS, exist_ok=True)
    while len(os.listdir(LOCKS)) >= MAX_SESSIONS:
        time.sleep(30)
    lock = os.path.join(LOCKS, tid)
    os.makedirs(lock)
    try:
        logs = os.path.join(LOGS, tid)
        os.makedirs(logs, exist_ok=True)
        pd = project_dir(w)
        if os.path.lexists(pd):
            os.remove(pd) if os.path.islink(pd) else sys.exit(f"{pd} exists and is not a symlink")
        os.symlink(logs, pd)
        hidden = [BENCH] + [os.path.join(root, d) for d in os.listdir(root) if d != tid]
        modes = {p: os.stat(p).st_mode for p in hidden}
        for p in hidden:
            os.chmod(p, 0)
        s = f"bench-{tid}"
        t0 = time.time()
        try:
            sh("tmux", "new-session", "-d", "-s", s, "-c", w, f"claude --dangerously-skip-permissions -n {s}")
            time.sleep(10)
            sh("tmux", "send-keys", "-t", s, "-l", "Read TASK.md and do the task. ./check.sh checks your work.")
            sh("tmux", "send-keys", "-t", s, "Enter")
            idle, deadline = 0, t0 + 60 * timeout_min
            while time.time() < deadline:
                time.sleep(20)
                pane = sh("tmux", "capture-pane", "-p", "-t", s, check=False).stdout
                idle = idle + 1 if ("esc to interrupt" not in pane) else 0
                if idle >= 6:   # two minutes without activity: done
                    break
            if not glob.glob(os.path.join(logs, "*.jsonl")):
                print(f"WARNING: no transcript in {logs}")
        finally:
            sh("tmux", "kill-session", "-t", s, check=False)
            for p, mo in modes.items():
                os.chmod(p, mo)
        json.dump({"task": tid, "baseline": baseline, "start": t0, "end": time.time(),
                   "timed_out": time.time() >= t0 + 60 * timeout_min},
                  open(os.path.join(logs, "run.json"), "w"))
    finally:
        os.rmdir(lock)


def collect(tid, root):
    logs = os.path.join(LOGS, tid)
    usage = {"input_tokens": 0, "output_tokens": 0, "cache_read_input_tokens": 0, "cache_creation_input_tokens": 0}
    turns = 0
    for p in glob.glob(os.path.join(logs, "*.jsonl")):
        for line in open(p):
            try:
                e = json.loads(line)
            except ValueError:
                continue
            msg = e.get("message") or {}
            if e.get("type") == "assistant" and isinstance(msg, dict) and "usage" in msg:
                turns += 1
                for k in usage:
                    usage[k] += msg["usage"].get(k, 0) or 0
    w = os.path.join(root, tid)
    r = subprocess.run(["./check.sh"], cwd=w, capture_output=True, text=True)
    out = r.stdout.strip().splitlines()[-1] if r.stdout.strip() else ""
    outcome = "proved" if out.startswith("PROVED") else "refuted" if out.startswith("REFUTED") else "unknown"
    res = {"task": tid, "outcome": outcome, "detail": out, "turns": turns, "usage": usage,
           "tokens": sum(usage.values())}
    run_ = os.path.join(logs, "run.json")
    if os.path.exists(run_):
        j = json.load(open(run_))
        res.update(wall_s=round(j["end"] - j["start"]), baseline=j["baseline"], timed_out=j["timed_out"])
    if outcome != "unknown" or os.path.exists(os.path.join(w, "B.elf")):
        res["speed"] = speed(w)
    json.dump(res, open(os.path.join(logs, "result.json"), "w"), indent=1)
    print(json.dumps(res, indent=1))


def speed(w):
    """Instructions and simulated cycles inside the function, A and B, per workload."""
    N = os.path.join(w, "tools/nocompiler")
    f = open(os.path.join(w, "FUNCTION")).read().strip()
    out = []
    for p in sorted(glob.glob(os.path.join(w, "workloads/*.bin"))):
        row = {"workload": os.path.basename(p)}
        for side in ("A", "B"):
            r = subprocess.run([N, "sim", f"{side}.elf", "--stdin", p, "--json"], cwd=w, capture_output=True, text=True)
            try:
                j = json.loads(r.stderr.strip().splitlines()[-1])
                fn = next((x for x in j["functions"] if x["name"] == f), None)
                row[side] = {"instructions": fn["instructions"], "cycles": fn["cycles"]} if fn else None
            except (ValueError, IndexError):
                row[side] = None
        out.append(row)
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    cmd = sys.argv[1]
    root = arg("--root", ROOT)
    if cmd == "list":
        for tid, t in tasks().items():
            print(f"{tid:36} {t['family']:14} {t['what']}")
    elif cmd == "prepare":
        prepare(sys.argv[2], arg("--baseline") or sys.exit("--baseline SHA"), root)
    elif cmd == "check":
        os.execv(os.path.join(sys.argv[2], "check.sh"), [os.path.join(sys.argv[2], "check.sh")])
    elif cmd == "run":
        run(sys.argv[2], arg("--baseline") or sys.exit("--baseline SHA"), root, int(arg("--timeout", "45")))
    elif cmd == "collect":
        collect(sys.argv[2], root)
    else:
        sys.exit(__doc__)


main()
